function recipe({
  id,
  name,
  aliases = [],
  category,
  description,
  base,
  required,
  steps,
  variants = [plain(), spice, ghee],
  art = 'curry',
  splitInstruction,
  finishBase = '',
  finishMinutes = 0,
  note = '',
}) {
  return {
    catalog: {
      id,
      name,
      aliases,
      category,
      description,
      art,
      tags: [category, 'Separate finishes'],
      variants: variants.map(v => ({ id: v.id, label: v.label })),
      defaultVariant: variants[0].id,
    },
    definition: {
      version: '2',
      defaultVariant: variants[0].id,
      requiredIngredients: required,
      base: amounts(base),
      extras: Object.fromEntries(variants.map(v => [v.id, amounts(v.ingredients)])),
      sharedSteps: steps,
      splitInstruction,
      finish: Object.fromEntries(variants.map(v => [v.id, `${v.instruction} ${finishBase}`.trim()])),
      finishMinutes: Object.fromEntries(variants.map(v => [v.id, v.minutes + finishMinutes])),
      note,
    },
  };
}

